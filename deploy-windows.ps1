# =============================================================
# deploy-windows.ps1
# One-click deployment script for zhengbao.work portfolio app
# Deploy dir: C:\deploy-zhengbao
# Express port: 3002
# Proxy: luzhougo main server forwards zhengbao.work -> :3002
# =============================================================
param(
    [switch]$OpenFirewall,
    [switch]$InstallStartupTask,
    [switch]$StartApp,
    [switch]$All
)

$ErrorActionPreference = "Stop"
$DeployDir = "C:\deploy-zhengbao"
$AppPort = 3002
$AppName = "zhengbao-portfolio"
$TaskName = "Startup_$AppName"
$RunScript = Join-Path $DeployDir "run-deploy-server.ps1"

# ---- Banner ----
Write-Host "============================================" -ForegroundColor Cyan
Write-Host " Deploy zhengbao.work Portfolio App" -ForegroundColor Cyan
Write-Host " Target: ${DeployDir}" -ForegroundColor Cyan
Write-Host " Port:   ${AppPort}" -ForegroundColor Cyan
Write-Host "============================================" -ForegroundColor Cyan

# ---- Check if running as Administrator ----
$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Host "WARNING: Not running as Administrator. Firewall and startup task features require admin rights." -ForegroundColor Yellow
}

# ---- 1. Verify / extract package ----
Write-Host "`n[1/5] Verifying deploy directory..." -ForegroundColor Yellow
if (-not (Test-Path $DeployDir)) {
    Write-Host "  Creating $DeployDir ..." -ForegroundColor Gray
    New-Item -ItemType Directory -Path $DeployDir -Force | Out-Null
}

# Check for deploy package files
$DistDir = Join-Path $DeployDir "dist"
$ServerFile = Join-Path $DeployDir "server\server.cjs"

if (-not (Test-Path $DistDir)) {
    Write-Host "  ERROR: dist/ not found in $DeployDir" -ForegroundColor Red
    Write-Host "  Please extract zhengbao-deploy.zip to $DeployDir first." -ForegroundColor Red
    exit 1
}

if (-not (Test-Path $ServerFile)) {
    Write-Host "  ERROR: $ServerFile not found" -ForegroundColor Red
    Write-Host "  Make sure you are using the latest zhengbao-deploy.zip (with server/ directory)." -ForegroundColor Red
    exit 1
}

Write-Host "  Package verified: server/server.cjs present" -ForegroundColor Green

# ---- 2. Install npm dependencies ----
Write-Host "`n[2/5] Installing npm dependencies..." -ForegroundColor Yellow
Set-Location $DeployDir
if (-not (Test-Path (Join-Path $DeployDir "package.json"))) {
    Write-Host "  ERROR: package.json not found in $DeployDir" -ForegroundColor Red
    exit 1
}
npm install --omit=dev --no-audit --no-fund
if ($LASTEXITCODE -ne 0) { throw "npm install failed" }
Write-Host "  Dependencies installed" -ForegroundColor Green

# ---- 3. Configure .env ----
Write-Host "`n[3/5] Checking .env configuration..." -ForegroundColor Yellow
$EnvFile = Join-Path $DeployDir ".env"
if (-not (Test-Path $EnvFile)) {
    Write-Host "  WARNING: .env not found. Creating template..." -ForegroundColor Yellow
    @"
# zhengbao.work Portfolio App - Environment Configuration
# Generated by deploy-windows.ps1 - fill in real values

NODE_ENV=production
PORT=$AppPort
APP_URL=http://localhost:$AppPort

# Supabase (PostgreSQL + Storage)
SUPABASE_URL=https://your-project.supabase.co
SUPABASE_SERVICE_ROLE_KEY=sb_secret_your_service_role_key_here
SUPABASE_STORAGE_BUCKET=portfolio-media

# Tencent Cloud COS (media storage)
TENCENT_COS_SECRET_ID=your_cos_secret_id
TENCENT_COS_SECRET_KEY=your_cos_secret_key
TENCENT_COS_BUCKET=your-bucket-name
TENCENT_COS_REGION=ap-guangzhou
TENCENT_COS_PUBLIC_BASE_URL=https://your-bucket.cos.ap-guangzhou.myqcloud.com

# Admin credentials
ADMIN_PHONE=your_phone
ADMIN_PASSWORD=your_password
ADMIN_SESSION_SECRET=your_session_secret

# Optional
MAX_UPLOAD_SIZE_MB=500
GEMINI_API_KEY=your_gemini_key
"@ | Out-File -FilePath $EnvFile -Encoding UTF8
    Write-Host "  .env template created at $EnvFile" -ForegroundColor Yellow
    Write-Host "  >>> IMPORTANT: Edit $EnvFile with real credentials before starting the app! <<<" -ForegroundColor Red
} else {
    Write-Host "  .env found" -ForegroundColor Green
}

# Ensure PORT is set correctly in .env
$envContent = Get-Content $EnvFile -Raw -Encoding UTF8
if ($envContent -notmatch "PORT=3002") {
    Write-Host "  WARNING: PORT may not be set to 3002 in .env. The run-deploy-server.ps1 will override it." -ForegroundColor Yellow
}

# ---- 4. Open Windows Firewall ----
if ($OpenFirewall -or $All) {
    Write-Host "`n[4/5] Configuring Windows Firewall..." -ForegroundColor Yellow
    if ($isAdmin) {
        $existingRule = Get-NetFirewallRule -DisplayName "Allow TCP $AppPort ($AppName)" -ErrorAction SilentlyContinue
        if ($existingRule) {
            Write-Host "  Firewall rule already exists" -ForegroundColor Gray
        } else {
            New-NetFirewallRule -DisplayName "Allow TCP $AppPort ($AppName)" -Direction Inbound -Protocol TCP -LocalPort $AppPort -Action Allow -Profile Any | Out-Null
            Write-Host "  Firewall rule added: Allow TCP $AppPort inbound" -ForegroundColor Green
        }
    } else {
        Write-Host "  SKIPPED: Firewall configuration requires Administrator rights" -ForegroundColor Yellow
    }
} else {
    Write-Host "`n[4/5] Skipping firewall (use -OpenFirewall to enable)" -ForegroundColor DarkYellow
}

# ---- 5. Install Windows startup task ----
if ($InstallStartupTask -or $All) {
    Write-Host "`n[5/5] Installing startup task..." -ForegroundColor Yellow
    if ($isAdmin) {
        # Unregister existing task if present
        $existingTask = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
        if ($existingTask) {
            Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
            Write-Host "  Removed existing startup task" -ForegroundColor Gray
        }

        # Create startup trigger (at system startup, delay 30s to let network init)
        $trigger = New-ScheduledTaskTrigger -AtStartup -RandomDelay (New-TimeSpan -Seconds 90)

        # Create action: run PowerShell with the run-deploy-server.ps1 start command
        $action = New-ScheduledTaskAction -Execute "PowerShell.exe" `
            -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$RunScript`" -Start"

        # Settings: hidden, don't stop on idle, restart on failure
        $settings = New-ScheduledTaskSettingsSet `
            -AllowStartIfOnBatteries `
            -DontStopIfGoingOnBatteries `
            -StartWhenAvailable `
            -RestartCount 3 `
            -RestartInterval (New-TimeSpan -Minutes 1) `
            -MultipleInstances IgnoreNew

        # Register task to run as SYSTEM
        Register-ScheduledTask -TaskName $TaskName `
            -Trigger $trigger `
            -Action $action `
            -Settings $settings `
            -Description "Auto-start zhengbao.work portfolio app on port $AppPort" `
            -User "SYSTEM" `
            -RunLevel Highest `
            -Force | Out-Null

        Write-Host "  Startup task registered: $TaskName" -ForegroundColor Green
        Write-Host "  App will auto-start after system reboot (30s delay)" -ForegroundColor Green
    } else {
        Write-Host "  SKIPPED: Startup task requires Administrator rights" -ForegroundColor Yellow
    }
} else {
    Write-Host "`n[5/5] Skipping startup task (use -InstallStartupTask to enable)" -ForegroundColor DarkYellow
}

# ---- Final: Start the app ----
if ($StartApp -or $All) {
    Write-Host "`nStarting application..." -ForegroundColor Yellow
    if (($InstallStartupTask -or $All) -and $isAdmin) {
        Start-ScheduledTask -TaskName $TaskName
        Start-Sleep -Seconds 5
    } else {
        & $RunScript -Start
    }
} else {
    Write-Host "`nDeployment setup complete. To start the app:" -ForegroundColor White
    Write-Host "  .\run-deploy-server.ps1 -Start" -ForegroundColor White
}

Write-Host "`n============================================" -ForegroundColor Cyan
Write-Host " Deployment Summary" -ForegroundColor Cyan
Write-Host "============================================" -ForegroundColor Cyan
Write-Host "  Directory:      $DeployDir" -ForegroundColor White
Write-Host "  Express port:   $AppPort" -ForegroundColor White
Write-Host "  Firewall:       $(if ($OpenFirewall -or $All) { 'Configured' } else { 'Skipped' })" -ForegroundColor White
Write-Host "  Startup task:   $(if ($InstallStartupTask -or $All) { 'Installed' } else { 'Skipped' })" -ForegroundColor White
Write-Host "  App running:    $(if ($StartApp -or $All) { 'Started' } else { 'Not started' })" -ForegroundColor White
Write-Host "`n  Test: curl http://localhost:$AppPort/health" -ForegroundColor White
Write-Host "============================================" -ForegroundColor Cyan
